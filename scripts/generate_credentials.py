#!/usr/bin/env python3
"""Credential generation script for OnionDrop.

Generates a secure Argon2id password hash and a cryptographically strong
session secret for use in the .env configuration.
"""

import argparse
import getpass
import secrets
import sys
from pathlib import Path
from argon2 import PasswordHasher, Type


def generate_session_secret(n_bytes: int = 48) -> str:
    """Generate a high-entropy session secret key."""
    return secrets.token_urlsafe(n_bytes)


def hash_password(password: str) -> str:
    """Hash password using Argon2id with OWASP-recommended parameters."""
    hasher = PasswordHasher(
        time_cost=3,
        memory_cost=65536,  # 64 MiB
        parallelism=4,
        hash_len=32,
        salt_len=16,
        type=Type.ID
    )
    return hasher.hash(password)


def main():
    parser = argparse.ArgumentParser(
        description="Generate Argon2 password hash and session secret for OnionDrop"
    )
    parser.add_argument(
        "--password",
        type=str,
        help="Password to hash (if omitted, will prompt securely)"
    )
    parser.add_argument(
        "--random-password",
        action="store_true",
        help="Generate a strong random password automatically"
    )
    parser.add_argument(
        "--write-env",
        action="store_true",
        help="Write generated credentials directly to .env file"
    )
    parser.add_argument(
        "--max-file-size",
        type=int,
        default=100,
        help="Maximum upload file size in MB (default: 100)"
    )

    args = parser.parse_args()

    plain_password = None
    if args.random_password:
        plain_password = secrets.token_urlsafe(24)
        print(f"[!] Generated Random Password: {plain_password}")
        print("    --> Save this password! It is required to log into OnionDrop.\n")
    elif args.password:
        plain_password = args.password
    else:
        while True:
            p1 = getpass.getpass("Enter upload password: ")
            if not p1:
                print("Error: Password cannot be empty.", file=sys.stderr)
                continue
            p2 = getpass.getpass("Confirm upload password: ")
            if p1 != p2:
                print("Error: Passwords do not match. Try again.\n", file=sys.stderr)
                continue
            plain_password = p1
            break

    print("[*] Computing Argon2id hash...")
    password_hash = hash_password(plain_password)
    session_secret = generate_session_secret()

    env_content = (
        f"# OnionDrop Environment Configuration\n"
        f"# Generated by scripts/generate_credentials.py\n\n"
        f"UPLOAD_PASSWORD_HASH={password_hash}\n"
        f"SESSION_SECRET={session_secret}\n"
        f"MAX_FILE_SIZE_MB={args.max_file_size}\n"
        f"COOKIE_SECURE=false\n"
        f"COOKIE_SAMESITE=lax\n"
        f"SESSION_EXPIRE_HOURS=4\n"
    )

    if args.write_env:
        env_path = Path(".env")
        if env_path.exists():
            overwrite = input(".env already exists. Overwrite? (y/N): ").strip().lower()
            if overwrite != "y":
                print("[*] Skipped writing to .env. Outputting to stdout instead:\n")
                print(env_content)
                return
        env_path.write_text(env_content, encoding="utf-8")
        print(f"[+] Successfully written credentials to {env_path.resolve()}\n")
    else:
        print("\n" + "=" * 60)
        print("Add the following configuration to your .env file:")
        print("=" * 60)
        print(env_content)
        print("=" * 60)


if __name__ == "__main__":
    main()
